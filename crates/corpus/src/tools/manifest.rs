//! `corpus/README.md` and `corpus/manifest.json`: what is in the corpus, generated from the files.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use serde::Serialize;

use crate::format::{Metadata, Origin, Scaling, Summary, EXTENSION};
use crate::reader::read_info;

#[derive(Debug, Serialize)]
struct Entry {
    file: String,
    size_bytes: u64,
    metadata: Metadata,
    summary: Option<Summary>,
}

/// Every corpus file in `dir`, sorted by name.
pub fn corpus_files(dir: &Path) -> Result<Vec<PathBuf>> {
    let mut files: Vec<PathBuf> = std::fs::read_dir(dir)
        .with_context(|| format!("read {}", dir.display()))?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == EXTENSION))
        .collect();
    files.sort();
    Ok(files)
}

/// Write `README.md` and `manifest.json` into `dir`. `report` is an encode report table to
/// include, if one was produced.
pub fn write(dir: &Path, report: Option<&str>) -> Result<()> {
    let mut entries = Vec::new();
    for f in corpus_files(dir)? {
        let size = std::fs::metadata(&f).map(|m| m.len()).unwrap_or(0);
        match read_info(&f) {
            Ok((metadata, summary)) => entries.push(Entry {
                file: f
                    .file_name()
                    .map(|n| n.to_string_lossy().into_owned())
                    .unwrap_or_default(),
                size_bytes: size,
                metadata,
                summary,
            }),
            Err(e) => tracing::warn!(file = %f.display(), "skipped in the manifest: {e:#}"),
        }
    }
    let total: u64 = entries.iter().map(|e| e.size_bytes).sum();

    let mut md = String::new();
    let _ = writeln!(md, "# Screen-content corpus\n");
    let _ = writeln!(
        md,
        "Generated by `afklink-corpus manifest` on {}. Do not edit: regenerate.\n",
        crate::format::now_rfc3339()
    );
    let _ = writeln!(
        md,
        "Recorded and synthesised screen sequences for the offline simulator (`crates/sim`). \
         Read them with `afklink_corpus::Reader` (see `crates/corpus/src/lib.rs`). Every frame \
         is lossless BGRA with its capture timestamp; gaps between timestamps are gaps in WGC delivery \
         (a still screen). Not in git: regenerate with `cargo run -p afklink-corpus --release -- gen all` \
         from the afklink-agent repository's root.\n"
    );
    let _ = writeln!(
        md,
        "{} files, {:.2} GB in total.\n",
        entries.len(),
        total as f64 / 1e9
    );
    let _ = writeln!(
        md,
        "| file | seconds | frames (unique / repeat) | deliveries/s | stored | origin | MB | MB/min |"
    );
    let _ = writeln!(md, "|---|---|---|---|---|---|---|---|");
    for e in &entries {
        let (secs, frames, uniq, rep) = e.summary.as_ref().map_or((0.0, 0, 0, 0), |s| {
            (
                s.duration_us as f64 / 1e6,
                s.frame_count,
                s.unique_frames(),
                s.repeat_frames,
            )
        });
        let stored = match &e.metadata.stored.scaling {
            Scaling::Native => format!(
                "{}x{} native",
                e.metadata.stored.width, e.metadata.stored.height
            ),
            Scaling::Scaler { max_h } => format!(
                "{}x{} (scaled to {max_h}p)",
                e.metadata.stored.width, e.metadata.stored.height
            ),
        };
        let origin = match &e.metadata.origin {
            Origin::Synthetic {
                generator, seed, ..
            } => format!("{generator}, seed {seed}"),
            Origin::Recorded { .. } => "recorded".into(),
        };
        let mb = e.size_bytes as f64 / 1e6;
        let _ = writeln!(
            md,
            "| `{}` | {:.1} | {} ({} / {}) | {:.1} | {} | {} | {:.1} | {:.1} |{}",
            e.file,
            secs,
            frames,
            uniq,
            rep,
            if secs > 0.0 {
                frames as f64 / secs
            } else {
                0.0
            },
            stored,
            origin,
            mb,
            if secs > 0.0 { mb / secs * 60.0 } else { 0.0 },
            if e.summary.is_none() {
                " **truncated**"
            } else {
                ""
            }
        );
    }
    let _ = writeln!(md, "\n## Scenarios\n");
    for e in &entries {
        let _ = writeln!(
            md,
            "### `{}`\n\n{}\n",
            e.metadata.scenario, e.metadata.description
        );
        match &e.metadata.origin {
            Origin::Synthetic {
                generator,
                seed,
                params,
                inputs,
            } => {
                let _ = writeln!(md, "- generator `{generator}`, seed {seed}");
                for i in inputs {
                    let _ = writeln!(md, "- input: {i}");
                }
                let _ = writeln!(
                    md,
                    "- parameters: `{}`",
                    serde_json::to_string(params).unwrap_or_default()
                );
            }
            Origin::Recorded { tool, note } => {
                let _ = writeln!(md, "- recorded with {tool}. {note}");
            }
        }
        let _ = writeln!(
            md,
            "- timing: {} (jitter {} us, repeats {})",
            e.metadata.timing.clock, e.metadata.timing.jitter_us, e.metadata.timing.duplicates
        );
        if let Some(s) = &e.summary {
            let _ = writeln!(
                md,
                "- {} key / {} inter / {} repeat frames; payload {:.1} MB key + {:.1} MB inter{}",
                s.key_frames,
                s.inter_frames,
                s.repeat_frames,
                s.bytes_key as f64 / 1e6,
                s.bytes_inter as f64 / 1e6,
                if s.dropped > 0 {
                    format!("; **{} deliveries dropped by the recorder**", s.dropped)
                } else {
                    String::new()
                }
            );
        }
        for n in &e.metadata.notes {
            let _ = writeln!(md, "- note: {n}");
        }
        md.push('\n');
    }
    if let Some(r) = report {
        let _ = writeln!(md, "## Encode report (production encoder settings)\n\n{r}");
    }
    let readme = dir.join("README.md");
    std::fs::write(&readme, md).with_context(|| format!("write {}", readme.display()))?;
    let json = dir.join("manifest.json");
    std::fs::write(&json, serde_json::to_vec_pretty(&entries)?)
        .with_context(|| format!("write {}", json.display()))?;
    tracing::info!(
        files = entries.len(),
        gb = total as f64 / 1e9,
        readme = %readme.display(),
        "manifest written"
    );
    Ok(())
}
