import { describe, expect, test } from "bun:test";
import { bumpCargoToml, checkLockChange } from "./cargo";

const TOML = `[workspace]
members = ["crates/core", "app/src-tauri"]

[workspace.package]
version = "0.1.0"
edition = "2021"

[workspace.dependencies]
tokio = { version = "1", features = ["rt"] }

[[bin]]
name = "x"
version = "9.9.9"
`;

describe("bumpCargoToml", () => {
  test("changes the one version line of [workspace.package] and nothing else", () => {
    const out = bumpCargoToml(TOML, "0.1.0", "0.1.1");
    expect(out).toBe(TOML.replace('version = "0.1.0"', 'version = "0.1.1"'));
  });

  test("refuses when the file does not say what cargo said, or says it twice or never", () => {
    expect(() => bumpCargoToml(TOML, "0.2.0", "0.2.1")).toThrow(/cargo видит/);
    const twice = TOML.replace('edition = "2021"', 'version = "0.1.0"');
    expect(() => bumpCargoToml(twice, "0.1.0", "0.1.1")).toThrow(/— 2/);
    const never = TOML.replace('version = "0.1.0"\n', "");
    expect(() => bumpCargoToml(never, "0.1.0", "0.1.1")).toThrow(/— 0/);
  });
});

const LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "afklink-core"
version = "0.1.0"
dependencies = [
 "tokio",
]

[[package]]
name = "tokio"
version = "1.47.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abc"
`;

describe("checkLockChange", () => {
  test("only our version lines moved: fine", () => {
    const after = LOCK.replace(
      'name = "afklink-core"\nversion = "0.1.0"',
      'name = "afklink-core"\nversion = "0.1.1"',
    );
    expect(() => checkLockChange(LOCK, after, "0.1.0", "0.1.1")).not.toThrow();
  });

  test("a registry package that moved too: refused", () => {
    const after = LOCK.replace('version = "0.1.0"', 'version = "0.1.1"').replace(
      "1.47.0",
      "1.48.0",
    );
    expect(() => checkLockChange(LOCK, after, "0.1.0", "0.1.1")).toThrow(/tokio/);
  });

  test("our version left behind: refused", () => {
    expect(() => checkLockChange(LOCK, LOCK, "0.1.0", "0.1.1")).toThrow(/afklink-core/);
  });
});
